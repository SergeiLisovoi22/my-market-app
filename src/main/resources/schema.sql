CREATE TABLE IF NOT EXISTS items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(255) NOT NULL,
  description VARCHAR(2000) NOT NULL,
  img_path VARCHAR(255) NOT NULL,
  price BIGINT NOT NULL CHECK (price BETWEEN 0 AND 1000000000)
);
CREATE TABLE IF NOT EXISTS cart_mutex (id BIGINT PRIMARY KEY);
MERGE INTO cart_mutex (id) KEY(id) VALUES (1);
CREATE TABLE IF NOT EXISTS cart_lines (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id BIGINT NOT NULL UNIQUE,
  count INT NOT NULL CHECK (count BETWEEN 1 AND 1000),
  CONSTRAINT fk_cart_item FOREIGN KEY (item_id) REFERENCES items(id)
);
CREATE TABLE IF NOT EXISTS purchase_orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  total_sum BIGINT NOT NULL CHECK (total_sum >= 0),
  created_at TIMESTAMP NOT NULL
);
CREATE TABLE IF NOT EXISTS order_lines (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL,
  item_id BIGINT NOT NULL,
  title VARCHAR(255) NOT NULL,
  price BIGINT NOT NULL CHECK (price BETWEEN 0 AND 1000000000),
  count INT NOT NULL CHECK (count BETWEEN 1 AND 1000),
  img_path VARCHAR(255),
  CONSTRAINT fk_order_lines_order FOREIGN KEY (order_id) REFERENCES purchase_orders(id)
);
